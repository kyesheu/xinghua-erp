import java.util.stream.Collectors;
import static org.junit.jupiter.api.Assertions.*;

class PurchaseStockInEntryTest {
    JdbcTemplate db;
    ErpPurchaseOrderShipServiceImpl service;
    @BeforeEach void setup() throws Exception {
        var ds = new JdbcDataSource(); ds.setURL("jdbc:h2:mem:"+UUID.randomUUID()+";MODE=MySQL;DB_CLOSE_DELAY=-1;LOCK_TIMEOUT=5000");
        new ResourceDatabasePopulator(new ClassPathResource("sales-shipping-schema.sql"), new ClassPathResource("local-after-sale-schema.sql")).execute(ds);
        db = new JdbcTemplate(ds);
        var config = new MybatisConfiguration();
        for (var type : List.of(ErpPurchaseOrderShipMapper.class, ErpPurchaseOrderMapper.class, ErpPurchaseOrderItemMapper.class,
                ErpWarehouseMapper.class, ErpStockInMapper.class, ErpStockInItemMapper.class)) config.addMapper(type);
        var factory = new MybatisSqlSessionFactoryBean(); factory.setDataSource(ds); factory.setConfiguration(config);
        var session = new SqlSessionTemplate(factory.getObject());
        createTable("erp_purchase_order",ErpPurchaseOrder.class);
        createTable("erp_purchase_order_ship",ErpPurchaseOrderShip.class);
        createTable("erp_purchase_order_item",ErpPurchaseOrderItem.class);
        db.update("INSERT INTO erp_purchase_order(id,status,merchant_id,shop_id) VALUES(1,2,7,10)");
        db.update("INSERT INTO erp_purchase_order_ship(id,order_id,order_num,status) VALUES(1,1,'PUR-1',1),(2,1,'PUR-1',1)");
        db.update("INSERT INTO erp_purchase_order_item(id,order_id,goods_id,spec_id,quantity,price,inventory_mode) VALUES(1,1,201,101,10,2,0)");
        db.update("INSERT INTO erp_warehouse(id,warehouse_type,warehouse_no,warehouse_name,status,merchant_id,warehouse_source) VALUES(1,'LOCAL','MAIN','测试仓',1,7,0)");
        var inventoryFacade = new cn.xinghuaerp.inventory.facade.InventoryFacadeImpl(
                session.getMapper(ErpStockInItemMapper.class), session.getMapper(ErpStockInMapper.class),
                null, null, session.getMapper(ErpWarehouseMapper.class), null, null);
        var target = new ErpPurchaseOrderShipServiceImpl(session.getMapper(ErpPurchaseOrderShipMapper.class),session.getMapper(ErpPurchaseOrderMapper.class),
                session.getMapper(ErpPurchaseOrderItemMapper.class),inventoryFacade, inventoryFacade, inventoryFacade);
        var proxy = new ProxyFactory(target); proxy.setProxyTargetClass(true);
        var interceptor = new TransactionInterceptor(new DataSourceTransactionManager(ds),new AnnotationTransactionAttributeSource());
        proxy.addAdvice(interceptor); service = (ErpPurchaseOrderShipServiceImpl)proxy.getProxy();
    }
    void createTable(String name,Class<?> type) {
        var fields = TableInfoHelper.getTableInfo(type).getFieldList().stream()
                .map(f -> f.getColumn()+" "+sqlType(f.getPropertyType())).collect(Collectors.joining(","));
        db.execute("CREATE TABLE "+name+" (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"+fields+")");
    }
    String sqlType(Class<?> type) {
        if (type == LocalDateTime.class) return "TIMESTAMP";
        if (type == BigDecimal.class) return "DECIMAL(12,2)";
        if (Number.class.isAssignableFrom(type)) return "BIGINT";
        return "VARCHAR(255)";
    }
    PurchaseOrderStockInBo request(long id) { var request = new PurchaseOrderStockInBo(); request.setId(id); request.setWarehouseId(1L); return request; }
    @AfterEach void close() { db.execute("SHUTDOWN"); }
    @Test void receiptUsesShipmentOrderRatherThanClientSuppliedOrder() {
        db.update("INSERT INTO erp_purchase_order(id,status,merchant_id,shop_id) VALUES(2,1,8,11)");
        db.update("UPDATE erp_purchase_order_ship SET status=0 WHERE id=1");
        db.update("UPDATE erp_purchase_order SET status=102 WHERE id=1");
        var receipt = new ErpPurchaseOrderShip(); receipt.setId(1L); receipt.setOrderId(2L); receipt.setUpdateBy("tester");
        receipt.setReceiptTime(LocalDateTime.of(2026,11,8,10,0));
        assertEquals(1,service.updateScmPurchaseOrderShip(receipt));
        assertEquals(2,db.queryForObject("SELECT status FROM erp_purchase_order WHERE id=1",Integer.class));
        assertEquals(1,db.queryForObject("SELECT status FROM erp_purchase_order WHERE id=2",Integer.class));
        assertEquals(receipt.getReceiptTime(),db.queryForObject("SELECT received_time FROM erp_purchase_order WHERE id=1",LocalDateTime.class));
        assertEquals(receipt.getReceiptTime(),db.queryForObject("SELECT receipt_time FROM erp_purchase_order_ship WHERE id=1",LocalDateTime.class));
        assertEquals(-2,service.updateScmPurchaseOrderShip(receipt));
    }
    @Test void receiptCannotReviveOrRegressAnOrderOutsideShippedState() {
        db.update("UPDATE erp_purchase_order_ship SET status=0 WHERE id=1");
        var receipt = new ErpPurchaseOrderShip(); receipt.setId(1L);
        receipt.setReceiptTime(LocalDateTime.of(2026,11,8,10,0));
        receipt.setUpdateBy("tester");
        for (int status : List.of(0,1,101,2,3,99)) {
            db.update("UPDATE erp_purchase_order SET status=? WHERE id=1",status);
            assertEquals(-2,service.updateScmPurchaseOrderShip(receipt));
            assertEquals(status,db.queryForObject("SELECT status FROM erp_purchase_order WHERE id=1",Integer.class));
            assertEquals(0,db.queryForObject("SELECT status FROM erp_purchase_order_ship WHERE id=1",Integer.class));
            assertNull(db.queryForObject("SELECT receipt_time FROM erp_purchase_order_ship WHERE id=1",LocalDateTime.class));
            assertNull(db.queryForObject("SELECT received_time FROM erp_purchase_order WHERE id=1",LocalDateTime.class));
        }
    }
    @Test void cancelledAndInvalidPurchaseCannotCreateTask() {
        db.update("UPDATE erp_purchase_order SET status=99 WHERE id=1");
        assertNotEquals(0,service.createStockInEntry(request(1),1L,"tester").getCode());
        db.update("UPDATE erp_purchase_order SET status=2 WHERE id=1");
        db.update("UPDATE erp_purchase_order_item SET quantity=-1 WHERE id=1");
        assertNotEquals(0,service.createStockInEntry(request(1),1L,"tester").getCode());
        assertEquals(0,db.queryForObject("SELECT COUNT(*) FROM erp_stock_in",Integer.class));
    }
    @Test void multipleShipmentsCannotCreateDuplicateFullOrderTasks() {
        assertEquals(0,service.createStockInEntry(request(1),1L,"tester").getCode());
        assertNotEquals(0,service.createStockInEntry(request(2),1L,"tester").getCode());
        assertEquals(1,db.queryForObject("SELECT COUNT(*) FROM erp_stock_in",Integer.class));
        assertEquals(1,db.queryForObject("SELECT COUNT(*) FROM erp_stock_in_item",Integer.class));
        assertEquals(1,db.queryForObject("SELECT status FROM erp_purchase_order_ship WHERE id=2",Integer.class));
    }
    @Test void concurrentShipmentsCreateOneTask() throws Exception {
        var pool=Executors.newFixedThreadPool(2); var start=new CountDownLatch(1);
        try {
            var a=pool.submit(()->{start.await();return service.createStockInEntry(request(1),1L,"tester").getCode();});
            var b=pool.submit(()->{start.await();return service.createStockInEntry(request(2),1L,"tester").getCode();});
            start.countDown(); assertNotEquals(a.get(10,TimeUnit.SECONDS)==0,b.get(10,TimeUnit.SECONDS)==0);
            assertEquals(1,db.queryForObject("SELECT COUNT(*) FROM erp_stock_in",Integer.class));
        } finally {pool.shutdownNow();}
    }
    @Test void failedDetailInsertRollsBackOrderAndShipment() {
        db.execute("ALTER TABLE erp_stock_in_item ADD CONSTRAINT reject_quantity CHECK(quantity <> 10)");
        assertThrows(RuntimeException.class,()->service.createStockInEntry(request(1),1L,"tester"));
        assertEquals(0,db.queryForObject("SELECT COUNT(*) FROM erp_stock_in",Integer.class));
        assertEquals(1,db.queryForObject("SELECT status FROM erp_purchase_order_ship WHERE id=1",Integer.class));
        assertEquals(2,db.queryForObject("SELECT status FROM erp_purchase_order WHERE id=1",Integer.class));
    }
}
