package cn.xinghuaerp.purchase.service;

import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.FileSystemResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.init.ResourceDatabasePopulator;

import java.nio.file.Path;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertEquals;

/**
 * 采购权限种子脚本（{@code docs/sql/ai-agent-permissions.sql}）中供应商档案维护权限的落库校验。
 *
 * <p>与 {@link AiRolePermissionSqlTest#permissionRegistrationIsIdempotentAndNeverGrantsRoles()} 互补：
 * 后者没有预置父菜单 2120，因此 {@code purchase:*} 语句永远不会执行；本用例显式预置 2120，
 * 用来锁定「新权限挂在真实存在的父菜单下、order_num 不冲突、重复执行不产生第二条、且不授予任何角色」。</p>
 *
 * @author qa
 */
class SupplierPermissionSqlTest
{
    private static final String SUPPLIER_PERMISSION = "purchase:supplier:manage";

    @Test
    void supplierPermissionIsRegisteredUnderPurchaseMenuOnceAndNeverGrantsRoles()
    {
        var ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=MySQL;DB_CLOSE_DELAY=-1");
        var db = new JdbcTemplate(ds);
        db.execute("CREATE TABLE sys_menu(menu_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "menu_name VARCHAR(50),parent_id BIGINT,order_num INT,path VARCHAR(100),"
                + "menu_type VARCHAR(1),visible VARCHAR(1),status VARCHAR(1),perms VARCHAR(100),"
                + "create_by VARCHAR(50),create_time TIMESTAMP,remark VARCHAR(200))");
        db.execute("CREATE TABLE sys_role_menu(role_id BIGINT,menu_id BIGINT)");

        // 预置：顶层菜单 9/906/916，以及真实存在的父菜单 2120（采购订单，目录类型）与两个既有采购权限
        db.update("INSERT INTO sys_menu(menu_id,menu_name,parent_id,order_num,menu_type,perms) VALUES "
                + "(9,'warehouse',NULL,NULL,'M',NULL),"
                + "(906,'in',9,NULL,'C',NULL),"
                + "(916,'out',9,NULL,'C',NULL),"
                + "(2120,'purchase_order',7,0,'C',NULL),"
                + "(2121,'采购单查询',2120,10,'F','purchase:order:query'),"
                + "(2122,'采购承运商维护',2120,50,'F','purchase:logistics:manage')");

        var populator = new ResourceDatabasePopulator(
                new FileSystemResource(Path.of("..", "..", "docs", "sql", "ai-agent-permissions.sql")));
        populator.execute(ds);
        populator.execute(ds);

        assertEquals(1, count(db, "SELECT COUNT(*) FROM sys_menu WHERE perms='" + SUPPLIER_PERMISSION + "'"),
                "重复执行脚本不得插入第二条同名权限");

        assertEquals("供应商档案维护",
                db.queryForObject("SELECT menu_name FROM sys_menu WHERE perms='" + SUPPLIER_PERMISSION + "'",
                        String.class));
        assertEquals(2120L, longValue(db, "SELECT parent_id FROM sys_menu WHERE perms='"
                + SUPPLIER_PERMISSION + "'"), "必须挂在真实存在的采购订单菜单（2120）下");
        assertEquals(60, intValue(db, "SELECT order_num FROM sys_menu WHERE perms='" + SUPPLIER_PERMISSION + "'"));
        assertEquals("F", db.queryForObject(
                "SELECT menu_type FROM sys_menu WHERE perms='" + SUPPLIER_PERMISSION + "'", String.class),
                "按钮级权限必须是 F");
        assertEquals("0", db.queryForObject(
                "SELECT status FROM sys_menu WHERE perms='" + SUPPLIER_PERMISSION + "'", String.class),
                "权限项必须为启用状态");

        assertEquals(0, count(db, "SELECT COUNT(*) FROM sys_menu a JOIN sys_menu b "
                        + "ON a.parent_id=b.parent_id AND a.order_num=b.order_num AND a.menu_id<b.menu_id "
                        + "WHERE a.parent_id=2120"),
                "order_num=60 不得与既有同级条目冲突");

        assertEquals(0, count(db, "SELECT COUNT(*) FROM sys_role_menu"), "脚本只能登记权限，不得给任何角色授权");

        db.execute("SHUTDOWN");
    }

    /**
     * 执行单值计数查询。
     *
     * @param db    JdbcTemplate
     * @param sql   计数 SQL
     * @return 计数结果
     */
    private static int count(JdbcTemplate db, String sql)
    {
        Integer value = db.queryForObject(sql, Integer.class);
        return value == null ? 0 : value;
    }

    /**
     * 执行单值 long 查询。
     *
     * @param db  JdbcTemplate
     * @param sql 查询 SQL
     * @return 结果
     */
    private static long longValue(JdbcTemplate db, String sql)
    {
        Number value = db.queryForObject(sql, Number.class);
        return value == null ? -1L : value.longValue();
    }

    /**
     * 执行单值 int 查询。
     *
     * @param db  JdbcTemplate
     * @param sql 查询 SQL
     * @return 结果
     */
    private static int intValue(JdbcTemplate db, String sql)
    {
        Number value = db.queryForObject(sql, Number.class);
        return value == null ? -1 : value.intValue();
    }
}
