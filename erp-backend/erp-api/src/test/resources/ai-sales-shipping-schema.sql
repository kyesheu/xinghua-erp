-- AI 采购草稿集成测试需要的商品与库存表（H2）。

CREATE TABLE IF NOT EXISTS o_goods (
  id bigint AUTO_INCREMENT,
  name varchar(50) NULL DEFAULT '',
  image varchar(255) NULL DEFAULT NULL,
  outer_erp_goods_id varchar(50) NULL DEFAULT NULL,
  goods_num varchar(50) NULL DEFAULT NULL,
  unit_name varchar(10) NULL DEFAULT '',
  category_id bigint NULL DEFAULT 0,
  bar_code varchar(60) NULL DEFAULT '',
  remark varchar(500) NULL DEFAULT '',
  status tinyint(1) DEFAULT 1,
  length float DEFAULT 0,
  height float DEFAULT 0,
  width float DEFAULT 0,
  width1 float DEFAULT 0,
  width2 float DEFAULT 0,
  width3 float DEFAULT 0,
  weight float DEFAULT 0,
  disable tinyint(1) DEFAULT 0,
  period varchar(10) NULL DEFAULT '0',
  pur_price double NULL DEFAULT 0,
  whole_price double NULL DEFAULT 0,
  retail_price double NULL DEFAULT 0,
  unit_cost double UNSIGNED NULL DEFAULT 0,
  supplier_id bigint NULL DEFAULT 0,
  brand_id bigint NULL DEFAULT 0,
  attr1 varchar(15) NULL DEFAULT NULL,
  attr2 varchar(15) NULL DEFAULT NULL,
  attr3 varchar(15) NULL DEFAULT NULL,
  attr4 varchar(15) NULL DEFAULT NULL,
  attr5 varchar(50) NULL DEFAULT NULL,
  link_url varchar(500) NULL DEFAULT NULL,
  low_qty int NULL DEFAULT 0,
  high_qty int NULL DEFAULT 0,
  create_by varchar(25) NULL DEFAULT NULL,
  create_time datetime NULL DEFAULT NULL,
  update_by varchar(25) NULL DEFAULT NULL,
  update_time datetime NULL DEFAULT NULL,
  province varchar(255) NULL DEFAULT NULL,
  city varchar(255) NULL DEFAULT NULL,
  town varchar(255) NULL DEFAULT NULL,
  ship_type int,
  merchant_id bigint,
  seller_id varchar(55) NULL DEFAULT NULL,
  seller_brand_id varchar(50) NULL DEFAULT NULL,
  price_type int DEFAULT 0,
  inventory_mode int DEFAULT 0,
  shop_id int DEFAULT 0,
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS o_goods_sku (
  id bigint AUTO_INCREMENT,
  goods_id bigint,
  outer_erp_goods_id varchar(50) NULL DEFAULT NULL,
  outer_erp_sku_id varchar(50) NULL DEFAULT NULL,
  goods_name varchar(255) NULL DEFAULT NULL,
  goods_num varchar(255) NULL DEFAULT NULL,
  sku_name varchar(100) NULL DEFAULT '',
  sku_code varchar(100),
  color_id bigint NULL DEFAULT 0,
  color_value varchar(50) NULL DEFAULT NULL,
  color_image varchar(100) NULL DEFAULT NULL,
  size_id bigint NULL DEFAULT 0,
  size_value varchar(50) NULL DEFAULT NULL,
  style_id bigint NULL DEFAULT 0,
  style_value varchar(50) NULL DEFAULT NULL,
  bar_code varchar(60) NULL DEFAULT NULL,
  pur_price decimal(8, 2) NULL DEFAULT 0.00,
  retail_price decimal(8, 2) NULL DEFAULT 0.00,
  unit_cost decimal(8, 2) NULL DEFAULT 0.00,
  remark varchar(50) NULL DEFAULT '',
  status tinyint(1) DEFAULT 1,
  low_qty int NULL DEFAULT 0,
  high_qty int NULL DEFAULT 0,
  ship_type int,
  volume varchar(255) NULL DEFAULT NULL,
  length float DEFAULT 0,
  height float DEFAULT 0,
  width float DEFAULT 0,
  weight float DEFAULT 0,
  merchant_id bigint,
  seller_id varchar(55) NULL DEFAULT NULL,
  seller_brand_id varchar(50) NULL DEFAULT NULL,
  unit varchar(10) NULL DEFAULT NULL,
  price_type int DEFAULT 0,
  weight1 float DEFAULT 0,
  weight2 float DEFAULT 0,
  weight3 float DEFAULT 0,
  inventory_mode int DEFAULT 0,
  shop_id int DEFAULT 0,
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS o_goods_sku_attr (
  id bigint AUTO_INCREMENT,
  goods_id bigint,
  type char(5) NULL DEFAULT NULL,
  k varchar(10) NULL DEFAULT NULL,
  kid int NULL DEFAULT NULL,
  vid int NULL DEFAULT NULL,
  v varchar(50) NULL DEFAULT NULL,
  img varchar(200) NULL DEFAULT NULL,
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS o_goods_inventory (
  id bigint AUTO_INCREMENT,
  goods_id bigint,
  goods_num varchar(20) NULL DEFAULT NULL,
  sku_id bigint,
  sku_code varchar(25) DEFAULT '',
  goods_name varchar(255) NULL DEFAULT NULL,
  goods_img varchar(255) NULL DEFAULT NULL,
  sku_name varchar(255) NULL DEFAULT NULL,
  quantity bigint DEFAULT 0,
  locked_quantity bigint DEFAULT 0,
  available_quantity bigint DEFAULT 0,
  warehouse_id bigint DEFAULT 0,
  merchant_id bigint DEFAULT 0,
  shop_id bigint DEFAULT 0,
  stock_status tinyint DEFAULT 1,
  is_delete tinyint(1) DEFAULT 0,
  create_time timestamp DEFAULT CURRENT_TIMESTAMP,
  create_by varchar(25) NULL DEFAULT NULL,
  update_time timestamp DEFAULT CURRENT_TIMESTAMP,
  update_by varchar(25) NULL DEFAULT NULL,
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS o_goods_inventory_batch (
  id bigint AUTO_INCREMENT,
  inventory_id bigint,
  batch_num varchar(50),
  origin_qty bigint DEFAULT 0,
  current_qty bigint DEFAULT 0,
  pur_price decimal(12, 2) NULL DEFAULT 0.00,
  pur_id bigint NULL DEFAULT 0,
  pur_item_id bigint NULL DEFAULT 0,
  remark varchar(250) NULL DEFAULT NULL,
  sku_id bigint DEFAULT 0,
  goods_id bigint DEFAULT 0,
  sku_code varchar(25) NULL DEFAULT NULL,
  warehouse_id bigint DEFAULT 0,
  position_id bigint NULL DEFAULT 0,
  position_num varchar(50) NULL DEFAULT NULL,
  merchant_id bigint DEFAULT 0,
  shop_id bigint DEFAULT 0,
  barcode varchar(100) NULL DEFAULT NULL,
  stock_status tinyint DEFAULT 1,
  inventory_mode tinyint DEFAULT 0,
  actual_gold_weight decimal(12, 4) NULL DEFAULT 0.0000,
  actual_silver_weight decimal(12, 4) NULL DEFAULT 0.0000,
  labor_cost decimal(12, 2) NULL DEFAULT 0.00,
  certificate_no varchar(50) NULL DEFAULT NULL,
  create_time timestamp DEFAULT CURRENT_TIMESTAMP,
  create_by varchar(25) NULL DEFAULT NULL,
  update_time timestamp DEFAULT CURRENT_TIMESTAMP,
  update_by varchar(25) NULL DEFAULT NULL,
  PRIMARY KEY (id)
);
