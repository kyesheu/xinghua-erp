package cn.xinghuaerp.ai.service;

import java.math.BigDecimal;
import cn.xinghuaerp.ai.service.AiPurchaseDraftService.Request;
import cn.xinghuaerp.common.ResultVo;
import cn.xinghuaerp.purchase.service.ErpPurchaseOrderService;
import java.util.UUID;
import java.util.concurrent.*;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.*;
import org.springframework.aop.framework.ProxyFactory;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.transaction.annotation.AnnotationTransactionAttributeSource;
import org.springframework.transaction.interceptor.TransactionInterceptor;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

class AiPurchaseDraftServiceTest {
    JdbcTemplate db;
    ErpPurchaseOrderService orders;
    AiPurchaseDraftService service;
    @BeforeEach void setup() {
        var ds = new JdbcDataSource(); ds.setURL("jdbc:h2:mem:"+UUID.randomUUID()+";MODE=MySQL;DB_CLOSE_DELAY=-1;LOCK_TIMEOUT=5000");
        db = new JdbcTemplate(ds);
        db.execute("CREATE TABLE ai_purchase_draft_request(request_key VARCHAR(36) PRIMARY KEY,user_id BIGINT NOT NULL,sku_id BIGINT NOT NULL,supplier_id BIGINT NOT NULL,quantity BIGINT NOT NULL,unit_price DECIMAL(8,2) NOT NULL,purchase_order_id BIGINT)");
        db.execute("CREATE TABLE fake_order(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)");
        db.execute("CREATE TABLE erp_supplier(id BIGINT PRIMARY KEY,name VARCHAR(100),disable INT,is_delete INT)");
        db.execute("CREATE TABLE erp_supplier_product_item(supplier_id BIGINT,erp_goods_sku_id BIGINT,status INT,supplier_product_id BIGINT)");
        db.execute("CREATE TABLE erp_supplier_product(id BIGINT,supplier_id BIGINT,status INT)");
        orders = mock(ErpPurchaseOrderService.class);
        when(orders.createPurchaseOrder(any())).thenAnswer(call -> {
            db.update("INSERT INTO fake_order DEFAULT VALUES");
            return ResultVo.success(db.queryForObject("SELECT MAX(id) FROM fake_order", Long.class));
        });
        var target = new AiPurchaseDraftService(db, orders); var proxy = new ProxyFactory(target); proxy.setProxyTargetClass(true);
        proxy.addAdvice(new TransactionInterceptor(new DataSourceTransactionManager(ds),new AnnotationTransactionAttributeSource()));
        service = (AiPurchaseDraftService) proxy.getProxy();
    }
    @AfterEach void close() { db.execute("SHUTDOWN"); }
    AiPurchaseDraftService.Request request(String key, long quantity) { return new AiPurchaseDraftService.Request(key,101L,10L,quantity,new BigDecimal("9.50")); }
    @Test void retryReturnsSameOrderAndRejectsChangesOrDifferentActor() {
        var key=UUID.randomUUID().toString(); var first=service.create(request(key,3),7L,"tester");
        var second=service.create(request(key,3),7L,"tester");
        assertFalse(first.replayed()); assertTrue(second.replayed()); assertEquals(first.orderId(),second.orderId());
        assertThrows(IllegalArgumentException.class,()->service.create(request(key,4),7L,"tester"));
        assertThrows(IllegalArgumentException.class,()->service.create(request(key,3),8L,"other"));
        assertEquals(1,db.queryForObject("SELECT COUNT(*) FROM fake_order",Integer.class));
    }
    @Test void failedOrderRollsBackIdempotencyRecord() {
        doAnswer(call -> {
            db.update("INSERT INTO fake_order DEFAULT VALUES");
            return ResultVo.error("无供应商关系");
        }).when(orders).createPurchaseOrder(any());
        assertThrows(IllegalArgumentException.class,()->service.create(request(UUID.randomUUID().toString(),1),7L,"tester"));
        assertEquals(0,db.queryForObject("SELECT COUNT(*) FROM ai_purchase_draft_request",Integer.class));
        assertEquals(0,db.queryForObject("SELECT COUNT(*) FROM fake_order",Integer.class));
    }
    @Test void concurrentRetriesCreateOnlyOneOrder() throws Exception {
        var key=UUID.randomUUID().toString(); var pool=Executors.newFixedThreadPool(2); var start=new CountDownLatch(1);
        try {
            var a=pool.submit(()->{start.await();return service.create(request(key,3),7L,"tester");});
            var b=pool.submit(()->{start.await();return service.create(request(key,3),7L,"tester");});
            start.countDown(); var x=a.get(10,TimeUnit.SECONDS); var y=b.get(10,TimeUnit.SECONDS);
            assertEquals(x.orderId(),y.orderId()); assertNotEquals(x.replayed(),y.replayed());
            assertEquals(1,db.queryForObject("SELECT COUNT(*) FROM fake_order",Integer.class));
        } finally {pool.shutdownNow();}
    }
    @Test void supplierChoicesExcludeDisabledAndDelistedRelations() {
        db.update("INSERT INTO erp_supplier VALUES(1,'可用',0,0),(2,'停用',1,0),(3,'下架',0,0),(4,'已删除',0,1)");
        db.update("INSERT INTO erp_supplier_product VALUES(1,1,1),(2,2,1),(3,3,1),(4,4,1)");
        db.update("INSERT INTO erp_supplier_product_item VALUES(1,101,1,1),(1,101,1,1),(2,101,1,2),(3,101,2,3),(4,101,1,4)");
        assertEquals(1, service.suppliers(101L).size());
        assertEquals("1", service.suppliers(101L).get(0).id());
        db.update("UPDATE erp_supplier_product SET status=2 WHERE id=1");
        assertTrue(service.suppliers(101L).isEmpty());
        db.update("UPDATE erp_supplier_product SET status=1,supplier_id=9 WHERE id=1");
        assertTrue(service.suppliers(101L).isEmpty());
        assertTrue(service.suppliers(999L).isEmpty());
    }
    @Test void recentDraftsAreOwnedAndOnlyExposeHeadquartersOrders() {
        db.execute("CREATE TABLE erp_purchase_order(id BIGINT,order_num VARCHAR(40),status INT,merchant_id BIGINT,shop_id BIGINT)");
        db.update("INSERT INTO erp_purchase_order VALUES(1,'OWN',102,0,0),(2,'OTHER',0,0,0),(3,'MERCHANT',0,7,0)");
        db.update("INSERT INTO ai_purchase_draft_request VALUES('a',7,101,10,3,9.5,1),('b',8,101,10,3,9.5,2),('c',7,101,10,3,9.5,3)");
        var rows = service.recent(7L);
        assertEquals(1, rows.size()); assertEquals("1", rows.get(0).orderId()); assertEquals(102, rows.get(0).status());
        assertThrows(IllegalArgumentException.class, () -> service.recent(null));
    }
}
