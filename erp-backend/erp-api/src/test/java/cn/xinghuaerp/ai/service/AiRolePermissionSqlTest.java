package cn.xinghuaerp.ai.service;

import com.baomidou.mybatisplus.core.MybatisConfiguration;
import cn.xinghuaerp.system.mapper.SysMenuMapper;
import com.baomidou.mybatisplus.extension.spring.MybatisSqlSessionFactoryBean;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.Test;
import org.mybatis.spring.SqlSessionTemplate;
import org.springframework.core.io.ClassPathResource;
import org.springframework.core.io.FileSystemResource;
import org.springframework.jdbc.datasource.init.ResourceDatabasePopulator;
import java.nio.file.Path;
import org.springframework.jdbc.core.JdbcTemplate;
import java.util.UUID;
import static org.junit.jupiter.api.Assertions.*;

class AiRolePermissionSqlTest {
    @Test void disabledAndDeletedRolesDoNotGrantPermissions() throws Exception {
        var ds = new JdbcDataSource(); ds.setURL("jdbc:h2:mem:"+UUID.randomUUID()+";MODE=MySQL;DB_CLOSE_DELAY=-1");
        var db = new JdbcTemplate(ds);
        db.execute("CREATE TABLE sys_menu(menu_id BIGINT,perms VARCHAR(100),status VARCHAR(1))");
        db.execute("CREATE TABLE sys_role_menu(role_id BIGINT,menu_id BIGINT)");
        db.execute("CREATE TABLE sys_user_role(role_id BIGINT,user_id BIGINT)");
        db.execute("CREATE TABLE sys_role(role_id BIGINT,status VARCHAR(1),del_flag VARCHAR(1))");
        db.update("INSERT INTO sys_menu VALUES(1,'ai:inventory:query','0'),(2,'ai:purchase:query','0'),(3,'ai:sales:query','0')");
        db.update("INSERT INTO sys_role VALUES(1,'0','0'),(2,'0','2'),(3,'1','0')");
        db.update("INSERT INTO sys_role_menu VALUES(1,1),(2,2),(3,3)");
        db.update("INSERT INTO sys_user_role VALUES(1,7),(2,7),(3,7)");
        var config = new MybatisConfiguration(); config.addMapper(SysMenuMapper.class);
        var factory = new MybatisSqlSessionFactoryBean(); factory.setDataSource(ds); factory.setConfiguration(config);
        factory.setMapperLocations(new ClassPathResource("mapper/system/SysMenuMapper.xml"));
        var mapper = new SqlSessionTemplate(factory.getObject()).getMapper(SysMenuMapper.class);
        assertEquals(java.util.List.of("ai:inventory:query"), mapper.selectMenuPermsByUserId(7L));
        db.execute("SHUTDOWN");
    }
    @Test void permissionRegistrationIsIdempotentAndNeverGrantsRoles() {
        var ds = new JdbcDataSource(); ds.setURL("jdbc:h2:mem:"+UUID.randomUUID()+";MODE=MySQL;DB_CLOSE_DELAY=-1");
        var db = new JdbcTemplate(ds);
        db.execute("CREATE TABLE sys_menu(menu_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,menu_name VARCHAR(50),parent_id BIGINT,order_num INT,path VARCHAR(100),menu_type VARCHAR(1),visible VARCHAR(1),status VARCHAR(1),perms VARCHAR(100),create_by VARCHAR(50),create_time TIMESTAMP,remark VARCHAR(200))");
        db.execute("CREATE TABLE sys_role_menu(role_id BIGINT,menu_id BIGINT)");
        db.update("INSERT INTO sys_menu(menu_id,menu_name) VALUES (9,'warehouse'),(906,'in'),(916,'out')");
        var populator = new ResourceDatabasePopulator(new FileSystemResource(Path.of("..","..","docs","sql","ai-agent-permissions.sql")));
        populator.execute(ds); populator.execute(ds);
        assertEquals(8,db.queryForObject("SELECT COUNT(*) FROM sys_menu WHERE perms IS NOT NULL",Integer.class));
        assertEquals(0,db.queryForObject("SELECT COUNT(*) FROM sys_role_menu",Integer.class));
        db.execute("SHUTDOWN");
    }

}
